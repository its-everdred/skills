#!/bin/bash

# Colors for output
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${YELLOW}🤖 Android Play Store Upload Setup${NC}"
echo ""

# Read the display name + slug from app.json so prompts and the per-app keystore
# name match the configured app (no hardcoded app identifiers).
APP_NAME=$(grep -o '"name": "[^"]*' app.json | grep -o '[^"]*$' | head -1)
APP_NAME="${APP_NAME:-your app}"
APP_SLUG=$(grep -o '"slug": "[^"]*' app.json | grep -o '[^"]*$' | head -1)
APP_SLUG="${APP_SLUG:-app}"

# Load any existing environment variables (line-by-line; preserves values verbatim)
if [ -f ".env" ]; then
    while IFS= read -r line || [ -n "$line" ]; do
        case "$line" in ''|\#*) continue ;; esac
        [ "${line#*=}" = "$line" ] && continue
        key="${line%%=*}"; value="${line#*=}"; value="${value%$'\r'}"; export "$key=$value"
    done < .env
fi

echo -e "${YELLOW}📱 Step 1: Create your app in Google Play Console${NC}"
echo ""
echo "1. Go to https://play.google.com/console"
echo "2. Click 'Create app'"
echo "3. Fill in:"
echo "   • App name: ${APP_NAME}"
echo "   • Default language: English"
echo "   • App or game: App"
echo "   • Free or paid: Free"
echo "4. Accept the declarations"
echo ""
echo -e "${YELLOW}Press Enter to open Google Play Console...${NC}"
read

open "https://play.google.com/console"

echo ""
echo -e "${YELLOW}Press Enter after creating your app...${NC}"
read

echo -e "${YELLOW}🔑 Step 2: (Optional) Create a service account for Play API access${NC}"
echo ""
echo "Note: the Play Console 'API access' page has been REMOVED. Service accounts are now"
echo "created and managed entirely in GOOGLE CLOUD CONSOLE, then granted access in Play."
echo "Uploading .aab files with this skill is MANUAL (via the Play Console web UI), so this"
echo "step is only needed if you later wire up your own API-based automation."
echo ""
echo "1. Select or create a Google Cloud project (opening now):"
echo "     https://console.cloud.google.com/projectcreate"
echo "2. Enable the Google Play Android Publisher API for that project (opening now):"
echo "     https://console.cloud.google.com/apis/library/androidpublisher.googleapis.com"
echo "   • Confirm the correct project is selected, then click 'Enable'."
echo "3. Create the service account (opening now):"
echo "     https://console.cloud.google.com/iam-admin/serviceaccounts → 'Create service account'"
echo "   • Name it e.g. play-upload; 'Create and continue'; SKIP Cloud roles; 'Done'."
echo "4. Create its JSON key:"
echo "     the service account → Actions (⋮) → 'Manage keys' → 'Add key' → 'Create new key' → JSON"
echo "5. Save the downloaded .json somewhere safe."
echo ""
open "https://console.cloud.google.com/apis/library/androidpublisher.googleapis.com" 2>/dev/null
open "https://console.cloud.google.com/iam-admin/serviceaccounts" 2>/dev/null
echo -e "${YELLOW}Press Enter to continue...${NC}"
read

echo -e "${YELLOW}📝 Step 3: Grant the service account access in Play Console${NC}"
echo ""
echo "In Play Console → Users and permissions (opening now):"
echo "     https://play.google.com/console/users-and-permissions"
echo "1. Click 'Invite new users'."
echo "2. Enter the service account email (…@….iam.gserviceaccount.com)."
echo "3. Under 'App access', grant JUST these (least privilege for an upload bot):"
echo "   • 'View app information (read-only)'"
echo "   • 'Release apps to testing tracks'"
echo "   • 'Release to production, exclude devices, and use Play App Signing'"
echo "       ^ only tick this if the bot should auto-publish to PRODUCTION; else leave off."
echo "   Do NOT grant Admin, Manage store presence, or financial permissions."
echo "4. Click 'Invite user'."
echo ""
echo "   Note: for a brand-new app, upload your FIRST release manually in the Console;"
echo "   the API will only accept uploads once an initial release exists."
echo ""
open "https://play.google.com/console/users-and-permissions" 2>/dev/null
echo ""
echo -e "${YELLOW}Press Enter to continue...${NC}"
read

echo -e "${YELLOW}🔐 Step 4: Generate upload keystore${NC}"
echo ""

# Use the same secure keystore location the upload script reads from, so the
# keystore survives `expo prebuild --clean` and is never regenerated by accident.
# The default filename is derived from the app slug so two apps never collide on
# one shared keystore.
KEYSTORE_PATH="${ANDROID_KEYSTORE_PATH:-$HOME/.private_keys/android/${APP_SLUG}-upload-keystore.jks}"
KEYSTORE_PATH="${KEYSTORE_PATH/#\~/$HOME}"
KEYSTORE_DIR=$(dirname "$KEYSTORE_PATH")
mkdir -p "$KEYSTORE_DIR"

# Record the resolved keystore path in .env so upload-android.sh (a fresh shell)
# resolves the identical location instead of falling back to the default — a
# mismatch here would sign with a different key and Play would reject the upload.
if [ -f .env ]; then
    grep -vE '^ANDROID_KEYSTORE_PATH=' .env > .env.tmp && mv .env.tmp .env
    echo "ANDROID_KEYSTORE_PATH=$KEYSTORE_PATH" >> .env
fi

if [ -f "$KEYSTORE_PATH" ]; then
    echo -e "${GREEN}✓ Keystore already exists: $KEYSTORE_PATH${NC}"
    echo -e "${RED}🔒 Existing keystore will NEVER be overwritten by this script.${NC}"
else
    echo "Generating Android upload keystore at: $KEYSTORE_PATH"

    # Generate secure passwords and capture them (they must match .env later)
    STORE_PASSWORD=$(openssl rand -base64 32 | tr -d "=+/" | cut -c1-25)
    KEY_PASSWORD=$(openssl rand -base64 32 | tr -d "=+/" | cut -c1-25)

    keytool -genkeypair -v \
        -storetype JKS \
        -keystore "$KEYSTORE_PATH" \
        -alias upload \
        -keyalg RSA \
        -keysize 2048 \
        -validity 10000 \
        -keypass "$KEY_PASSWORD" \
        -storepass "$STORE_PASSWORD" \
        -dname "CN=${APP_NAME}, OU=Development, O=${APP_NAME}, L=City, ST=State, C=US"

    if [ ! -f "$KEYSTORE_PATH" ]; then
        echo -e "${RED}❌ Error: Keystore creation failed${NC}"
        exit 1
    fi

    # Persist passwords to .env, replacing any prior (placeholder) lines so the
    # real keystore passwords are authoritative and never duplicated/shadowed.
    if [ -f .env ]; then
        grep -vE '^(# Android Release Signing$|ANDROID_UPLOAD_STORE_PASSWORD=|ANDROID_UPLOAD_KEY_PASSWORD=)' .env > .env.tmp && mv .env.tmp .env
    fi
    {
        echo ""
        echo "# Android Release Signing"
        echo "ANDROID_UPLOAD_STORE_PASSWORD=$STORE_PASSWORD"
        echo "ANDROID_UPLOAD_KEY_PASSWORD=$KEY_PASSWORD"
    } >> .env

    echo -e "${GREEN}✓ Keystore generated${NC}"
    echo -e "${YELLOW}⚠️  Passwords saved to .env (ANDROID_UPLOAD_*)${NC}"
    echo -e "${RED}⚠️  IMPORTANT: Back up this keystore file! You cannot regenerate it.${NC}"
fi

echo ""
echo -e "${YELLOW}📄 Step 5: .env configuration${NC}"
echo ""
if [ -f .env ]; then
    echo -e "${GREEN}✓ ANDROID_KEYSTORE_PATH recorded in .env:${NC} $KEYSTORE_PATH"
else
    echo "No .env found — run 'npm run setup:env' first, then add the keystore path:"
    echo -e "${BLUE}ANDROID_KEYSTORE_PATH=$KEYSTORE_PATH${NC}"
fi
echo ""

echo -e "${GREEN}✅ Setup complete!${NC}"
echo ""
echo "Next steps:"
echo "1. Confirm your .env has ANDROID_KEYSTORE_PATH and ANDROID_UPLOAD_* values"
echo "2. Run: npm run upload:android"
