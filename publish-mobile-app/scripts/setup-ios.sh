#!/bin/bash
# setup-ios.sh — one-time iOS onboarding.
#
# Runs automatically the first time you `npm run ios` (see run-ios.sh), and can
# be re-run any time. It:
#   1. Preflights the toolchain and installs the iOS platform if missing.
#   2. Generates the native ios/ project (expo prebuild) if it isn't there.
#   3. Optionally walks you through code signing — needed ONLY for physical
#      devices / TestFlight, not for the Simulator.
# On success it drops a sentinel so `npm run ios` won't re-run onboarding.

GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; NC='\033[0m'

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PROJECT_ROOT" || exit 1
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SENTINEL=".expo/.ios-setup-complete"

echo -e "${YELLOW}🔧 iOS onboarding${NC}"

# 1. Toolchain + platform preflight (required for BOTH simulator and device).
if ! "${SCRIPT_DIR}/doctor-ios.sh"; then
    echo -e "${RED}❌ Toolchain preflight failed — fix the above and re-run 'npm run setup:ios'.${NC}"
    exit 1
fi

# Load environment variables (line-by-line; preserves values verbatim). The
# signing step below needs APPLE_TEAM_ID; the simulator path needs nothing.
if [ -f ".env" ]; then
    while IFS= read -r line || [ -n "$line" ]; do
        case "$line" in ''|\#*) continue ;; esac
        [ "${line#*=}" = "$line" ] && continue
        key="${line%%=*}"; value="${line#*=}"; value="${value%$'\r'}"; export "$key=$value"
    done < .env
fi

# Fall back to the Apple Team ID configured in app.json when it is not in .env.
if [ -z "${APPLE_TEAM_ID:-}" ]; then
    APPLE_TEAM_ID=$(grep -o '"appleTeamId": "[^"]*' app.json | grep -o '[^"]*$' | head -1)
    export APPLE_TEAM_ID
fi

# 2. Ensure the native ios/ project exists so there is something to build/open.
if [ ! -d "ios" ]; then
    echo -e "${YELLOW}📦 Generating native iOS project (expo prebuild)...${NC}"
    if ! npx expo prebuild --platform ios; then
        echo -e "${RED}❌ expo prebuild failed.${NC}"
        exit 1
    fi
fi

# 3. Code signing is only needed to run on a physical device or upload to
#    TestFlight — the Simulator needs none of it. Offer it, but let
#    simulator-only devs skip straight through. Force with IOS_SETUP_SIGNING=1.
SETUP_SIGNING="${IOS_SETUP_SIGNING:-}"
if [ -z "$SETUP_SIGNING" ]; then
    if [ -t 0 ]; then
        echo ""
        echo -e "${YELLOW}Set up code signing now?${NC} Needed only for a physical device or"
        echo    "TestFlight upload — NOT for the iOS Simulator."
        printf  "Configure signing? [y/N] "
        read -r answer
        case "$answer" in [Yy]*) SETUP_SIGNING=1 ;; *) SETUP_SIGNING=0 ;; esac
    else
        SETUP_SIGNING=0
    fi
fi

if [ "$SETUP_SIGNING" = "1" ]; then
    echo -e "${YELLOW}📱 Step 1: Register your test device${NC}"
    echo ""
    echo "You need at least one device registered to create provisioning profiles."
    echo ""
    echo -e "${GREEN}To find your device UDID:${NC}"
    echo "  1. Connect your iPhone/iPad via USB"
    echo "  2. Option + click Apple menu → System Information"
    echo "  3. Click USB → select your device"
    echo "  4. Copy the 40-character Serial Number (that's the UDID)"
    echo ""
    echo -e "${YELLOW}Press Enter to open Apple Developer portal to register your device...${NC}"
    read -r

    open "https://developer.apple.com/account/resources/devices/add"

    echo ""
    echo "Register your device with:"
    echo "  • Platform: iOS"
    echo "  • Device Name: Any name (e.g., 'My iPhone')"
    echo "  • Device ID (UDID): The 40-character ID from above"
    echo ""
    echo -e "${YELLOW}Press Enter after registering your device...${NC}"
    read -r

    # Detect the workspace + project name generated by prebuild (derived from
    # the app name; do not hardcode a project name here).
    WORKSPACE=$(ls -d ios/*.xcworkspace 2>/dev/null | head -1)
    if [ -z "$WORKSPACE" ]; then
        echo -e "${RED}❌ Error: no .xcworkspace found in ios/. Did prebuild succeed?${NC}"
        exit 1
    fi
    PROJECT_NAME="$(basename "${WORKSPACE%.xcworkspace}")"

    echo -e "${YELLOW}📝 Step 2: Configure Xcode signing${NC}"
    echo -e "${GREEN}Please follow these steps in Xcode:${NC}"
    echo "1. Go to Xcode → Settings → Accounts"
    echo "2. Add your Apple Developer account if not already added"
    echo "3. Select the ${PROJECT_NAME} project in the navigator"
    echo "4. Select the ${PROJECT_NAME} target"
    echo "5. Go to Signing & Capabilities tab"
    echo "6. Check 'Automatically manage signing'"
    echo "7. Select your team: ${APPLE_TEAM_ID:-<your APPLE_TEAM_ID from .env>}"
    echo "8. Xcode should now create provisioning profiles"
    echo "9. Close Xcode when done"
    echo ""
    echo -e "${YELLOW}Press Enter to open Xcode...${NC}"
    read -r

    open "$WORKSPACE"

    echo ""
    echo -e "${YELLOW}Press Enter after you've configured signing in Xcode...${NC}"
    read -r

    echo -e "${GREEN}✓ Xcode signing configuration complete! You can now run: npm run upload:ios${NC}"
else
    echo -e "${GREEN}✓ Skipping signing setup — the Simulator needs nothing more.${NC}"
    echo    "  Set it up later for device/TestFlight with:  IOS_SETUP_SIGNING=1 npm run setup:ios"
fi

# 4. Mark onboarding complete so 'npm run ios' won't re-run this.
mkdir -p .expo
: > "$SENTINEL"
echo -e "${GREEN}✓ iOS onboarding complete. 'npm run ios' will now launch the Simulator directly.${NC}"
